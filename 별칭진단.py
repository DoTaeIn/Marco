# -*- coding: utf-8 -*-
"""남의 말을 빨아들이는 노드를 찾는다. 바꿔 말하기가 왜 지는지의 자리.

    python 별칭진단.py                    # 전체 그래프
    python 별칭진단.py graphs/graph_의료.kg
    python 별칭진단.py --개수 30

지능 시험에서 바꿔 말하기가 42.9% 였다. 파 보니 고칠 데가 알고리즘이
아니었다. 다섯 가지를 재보고 다 접었다.

    되묻기 바닥(A_MIN)을 낮춘다     건진 것 0개 · 엉뚱한 되묻기 1 -> 8 · 밖 27 -> 26
    틀 n그램을 눌러본다(IDF)        5/14 -> 1/14 로 **더 나빠진다**
    사전 뜻을 별칭으로 붙인다        등수 44 -> 19, 45 -> 15. 1등엔 못 간다
    말뭉치에서 같이 나오는 것을 센다   재료가 없다(트로포닌 0문서 · 목격자 6문서)
    긴 별칭을 길이로 눌러본다        2/14 -> 3/14. +1

노드 이름은 대개 지어낸 복합어라 사전이 못 덮는다(기초사전 2.0% · 위키
정의문 2.6%). 증거 매칭은 0/14 인데 그건 원래 글자 그대로 찾는 길이다.

그래도 하나는 깨끗하게 갈렸다. 노드마다 '남의 별칭을 대면 이 노드가 받는
평균 점수' 를 재면 이렇게 나온다.

    침해의현재성 0.346  적법행위 0.345  과잉방위불벌 0.341   <- 개념 노드
    압수된흉기 0.063  CCTV 0.058  근무일지 0.050         <- 증거 노드

개념 노드는 별칭이 16~24자짜리 문장이고 증거 노드는 5~8자짜리 이름이다.
포함도는 '물음의 조각이 별칭에 얼마나 덮이나' 라서, 긴 문장은 아무 물음의
말투('~있습니다', '~보면')를 통째로 덮는다. 그래서 '병원에서 떼 온 상해
소견 서류가 있습니다' 가 진단서(0.14)가 아니라 상당성(0.59)으로 간다.
내용이 아니라 길이가 이긴 것이다.

이 파일은 그 자리를 센다. 흡수력이 높은 노드는 둘 중 하나다.

    별칭이 설명문이다   -> 짧게 줄이거나, 설명은 [공리] 로 옮긴다
    쓰임이 실제로 넓다   -> 그대로 두되, 그 그래프에서 증거가 밀린다는 뜻이다

지어내지 않는다. 이 파일은 목록만 내고 아무것도 고치지 않는다.

**재 봤지만 안 되는 지표** — 적어 둔다. '별칭이 몇 개인가' 와 '별칭끼리
얼마나 다른가(넓이)' 로 위험을 예측해 보려 했는데 못 가른다. 놓친 노드의
넓이가 0.67~2.78, 맞힌 노드가 0.90~3.97 로 겹친다. 별칭 하나를 빼고 그
별칭으로 되찾는 시험도 1.1% 만 걸리는데, 손으로 적은 별칭끼리는 글자가
겹쳐서 쉬운 문제이기 때문이다. 결과는 그 노드가 아니라 **같은 그래프에
누가 같이 있느냐**가 정한다. 그래서 흡수력만 낸다.
"""
import glob
import itertools
import os
import sys

여기 = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, 여기)
os.environ.setdefault("KG_ENCODER", "문자")

import engine                                    # noqa: E402
from 진행 import 막대                             # noqa: E402

_표본 = 40                                       # 노드당 남의 말 몇 개까지 볼까


def 그래프들(인자):
    if 인자:
        return [p for p in 인자 if p.endswith(".kg")]
    return sorted(glob.glob(os.path.join(여기, "graphs", "*.kg")))


def _글자수(s):
    return len("".join(s.split()))


def 흡수력(경로):
    """-> [(흡수력, 노드, 별칭최대길이, 별칭수)] 높은 순."""
    이름 = os.path.relpath(경로, 여기).replace("\\", "/")
    g = engine.그래프불러오기(이름)
    층별 = {}
    for 층 in ("공통층", "사례층"):
        for n, 말들 in (g.get(층) or {}).items():
            층별[n] = list(말들) or [n]
    표 = []
    for n, 내별칭 in 층별.items():
        남 = [m for k, 말들 in 층별.items() if k != n for m in 말들][:_표본]
        if not 남:
            continue
        점 = [max(float(engine._속(q) @ engine._담(b)) for b in 내별칭) for q in 남]
        표.append((sum(점) / len(점), n,
                   max(_글자수(x) for x in 내별칭), len(내별칭)))
    return sorted(표, reverse=True)


def 보기(인자):
    개수 = 20
    if "--개수" in 인자:
        개수 = int(인자[인자.index("--개수") + 1])
    파일들 = 그래프들([a for a in 인자 if not a.startswith("--")])
    모두 = []
    for p in 막대(파일들, "흡수력"):
        try:
            for 점, n, 길, 수 in 흡수력(p):
                모두.append((점, os.path.basename(p), n, 길, 수))
        except Exception:
            continue
    if not 모두:
        print("잴 노드가 없다.")
        return
    모두.sort(reverse=True)
    중간 = 모두[len(모두) // 2][0]
    print("\n노드 %d개 · 흡수력 중앙값 %.3f" % (len(모두), 중간))
    print("\n남의 말을 가장 많이 빨아들이는 노드:")
    for 점, 파일, n, 길, 수 in 모두[:개수]:
        print("  %.3f  %-24s %-18s 별칭 %d개 · 최대 %d자"
              % (점, 파일[:24], n[:18], 수, 길))
    print("\n가장 안 빨아들이는 노드 (짧은 증거 이름이 여기 모인다):")
    for 점, 파일, n, 길, 수 in 모두[-5:]:
        print("  %.3f  %-24s %-18s 별칭 %d개 · 최대 %d자"
              % (점, 파일[:24], n[:18], 수, 길))


def _자가검사():
    # 긴 별칭이 짧은 별칭보다 남의 말을 더 덮는다 — 이 파일의 전제다.
    긴 = "피고인이 그 자리에서 계속 때렸다고 보입니다"
    짧 = "CCTV"
    물음 = "병원에서 떼 온 상해 소견 서류가 있습니다"
    v = engine._속(물음)
    assert float(v @ engine._담(긴)) > float(v @ engine._담(짧)), "전제가 깨졌다"
    assert _글자수("가 나 다") == 3
    assert 그래프들(["graphs/graph.kg"]) == ["graphs/graph.kg"]
    assert 그래프들([]), "그래프를 못 찾는다"
    print("자가검사 ok")


if __name__ == "__main__":
    인자 = sys.argv[1:]
    if "--자가검사" in 인자:
        _자가검사()
    else:
        보기(인자)
