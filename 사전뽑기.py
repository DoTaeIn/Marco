# -*- coding: utf-8 -*-
"""국어사전 뜻풀이에서 유(類)·동작·대상을 뽑는다.

왜 백과사전이 아니라 사전인가. 위키백과는 고유명사와 전문용어를 정의하지
일상 행위를 정의하지 않는다. 정작 필요했던 낱말이 이랬다.

    세차 · 독서          문서가 아예 없다
    연주 · 합주 · 수술    동음이의 문서만 있다("연주의 다른 뜻은 다음과 같다")

국어사전에는 다 있고, 게다가 꼴이 더 쉽다. 계사(~이다)를 안 거치고
유가 마침표 앞에 바로 오며, 서술성 명사형(함/음/-기)이 동작을 표시한다.

    세차   : 자동차의 안을 청소하거나 바깥에 묻은 먼지나 흙 등을 씻음.
    설거지 : 음식을 먹고 난 뒤에 그릇을 씻어서 정리함.
    세탁   : 더러운 옷 등을 빠는 일.

재료는 국립국어원 한국어기초사전(krdict)이다. CC BY-SA 2.0 KR 이라
라이선스가 깨끗하고, spellcheck-ko/korean-dict-nikl 에 XML 로 재배포돼 있어
회원가입 없이 받는다(공식 사이트는 로그인이 필요하다).

잰 것 (명사 표제어 30,227개):

    유 뽑힘 28,308 · 동작 9,643 · 대상 5,975
    빈 낱말 앞에서 멈춘 뿌리 기준 상위 30개가 낱말의 55.9% 를 덮는다
    (같은 잣대로 위키백과는 47.7% 였고 뿌리가 '말한'·'의미한' 같은 파편이었다)

뿌리는 물체(2,776) · 구역(1,990) · 모양(1,456) · 공간(914) · 도구(532) ·
음식(333) · 옷(177) 처럼 도식을 붙일 수 있는 것들이다.
"""
import re
# '것' 은 뺀다. '…나타낸 것' 은 사물이지 동작이 아니다.
동작류 = ("일", "행위", "짓", "활동", "작업", "과정", "절차", "놀이", "경기", "운동")
_유끝 = re.compile(r"([가-힣]{1,10})\s*$")
# 임자(의)가 붙은 목적어가 우선이다. '자동차의 안을' 의 대상은 '자동차' 다.
_목적어 = re.compile(r"(?:([가-힣]{1,12})의\s+)?(?:한\s+)?([가-힣]{1,12})(?:\s*등)?\s*(?:을|를)\s")
# 을/를 이 없으면 '~에' 를 본다. '산에 오름' 의 대상은 산이다.
_에격 = re.compile(r"([가-힣]{1,12})(?:\s*등)?\s*에\s+[가-힣]")
_버릴 = {"것", "수", "때", "곳", "바", "등", "이", "그", "저", "말", "데", "위", "안", "속", "중"}

def _명사형(말):
    """'오름'·'씻음'·'함' 처럼 ㅁ 받침으로 끝나거나 '-기' 로 끝나면 서술성 명사다."""
    if not 말:
        return False
    if 말.endswith("기"):
        return True
    끝 = 말[-1]
    return "가" <= 끝 <= "힣" and (ord(끝) - 0xAC00) % 28 == 16      # 종성 ㅁ

# 둘째 뜻은 잘라낸다. '…않음. 또는 그런 대상.' 에서 뒷말을 유로 잡으면
# '대상' 이 12,782번 나온다 — 표제어 넷 중 하나가 같은 뿌리로 몰렸다.
_둘째뜻 = re.compile(r"\.\s*또는|\s또는\s")

def 뽑기(뜻):
    """사전 뜻풀이 -> (유, 동작인가, 대상). 명사 표제어에만 쓴다 —
    동사 뜻풀이는 '…하다' 로 끝나 유가 안 나온다."""
    s = _둘째뜻.split((뜻 or "").strip(), 1)[0].strip().rstrip(".")
    if not s:
        return None, False, None
    m = _유끝.search(s)
    유 = m.group(1) if m else None
    동 = _명사형(유) or (유 in 동작류)
    후보 = [(임자, 몸) for 임자, 몸 in _목적어.findall(s)]
    대상 = None
    임자있는 = [a for a, _b in 후보 if a and a not in _버릴]
    if 임자있는:
        대상 = 임자있는[0]                      # 임자가 붙은 것이 더 또렷하다
    else:
        for _a, b in 후보:
            if b not in _버릴:
                대상 = b                        # 없으면 마지막 목적어
    if 대상 is None:
        e = _에격.search(s)
        if e and e.group(1) not in _버릴:
            대상 = e.group(1)
    return 유, 동, 대상


# 뜻풀이가 '…하는 것' 으로 끝나는 일이 잦은데 '것' 은 빈 낱말이라 도식을 못
# 붙인다. 사슬이 여기 닿으면 한 칸 앞에서 멈춘다 — 안 멈추면 낱말 넷 중
# 셋이 '것' 하나로 몰린다(11,989개를 그렇게 잃었다).
빈말 = {"것", "일", "있음", "됨", "함", "수", "바", "데", "때", "곳", "이", "그", "저",
        "않음", "아니함", "모두", "전부", "하나", "쪽", "편"}


def 뿌리찾기(말, 유맵, 최대=12):
    """유 사슬의 끝. 빈 낱말 앞에서 멈춘다.

    유는 그 자체로 낱말이라 제 유를 또 갖는다. 그 사슬을 따라가면 뿌리 몇
    개로 모이므로, 뿌리에 한 번 적은 것이 낱말 수천 개에 걸린다."""
    본 = set()
    while 말 in 유맵 and 말 not in 본 and 최대:
        본.add(말)
        다음 = 유맵[말]
        if 다음 in 빈말:
            return 말
        말, 최대 = 다음, 최대 - 1
    return 말


def _selfcheck():
    표본 = [("세차", "자동차의 안을 청소하거나 바깥에 묻은 먼지나 흙 등을 씻음.", True, "자동차"),
            ("설거지", "음식을 먹고 난 뒤에 그릇을 씻어서 정리함.", True, "그릇"),
            ("세탁", "더러운 옷 등을 빠는 일.", True, "옷"),
            ("독서", "책을 읽음.", True, "책"),
            ("등산", "산에 오름.", True, "산"),
            ("수술", "병을 고치기 위하여 몸의 한 부분을 째고 자르거나 꿰매는 일.", True, "몸"),
            ("가건물", "임시로 사용하기 위해 지은 건물.", False, None)]
    for 말, 뜻, 동기대, 대기대 in 표본:
        유, 동, 대 = 뽑기(뜻)
        assert 동 is 동기대, (말, 동, 동기대)
        assert 대 == 대기대, (말, 대, 대기대)
    # 임자(의)가 붙은 목적어가 이긴다. '자동차의 안을' 은 '안' 이 아니라 '자동차' 다.
    assert 뽑기("자동차의 안을 씻음.")[2] == "자동차"
    # 둘째 뜻은 자른다. 안 자르면 '대상' 하나로 12,782개가 몰린다.
    assert 뽑기("공격하기 어려워 무너지지 않음. 또는 그런 대상.")[0] == "않음"
    # 유는 사물 쪽에서 그대로 나온다
    assert 뽑기("작은 규모로 물건을 펼쳐 놓고 파는 집.")[0] == "집"
    # 빈 낱말 앞에서 멈춘다
    assert 뿌리찾기("세차", {"세차": "씻음", "씻음": "것"}) == "씻음"
    assert 뿌리찾기("가게", {"가게": "집", "집": "건물"}) == "건물"
    print("selfcheck ok")


if __name__ == "__main__":
    import sys
    if "--check" in sys.argv:
        _selfcheck()
    else:
        print(__doc__)
