# -*- coding: utf-8 -*-
"""HOI 분류기 출력을 그래프 엣지 **후보**로 옮긴다. 답으로 옮기지 않는다.

왜 이 파일이 있나. 분류기가 낸 점수를 그대로 답이라고 하면, 이 프로젝트가
피하려던 자리로 돌아간다 — 틀렸을 때 가리킬 파일 줄이 없는 상태. 학습된
가중치는 읽을 수도 되돌릴 수도 없으므로 **지식이 될 수 없다.**

그래서 분류기를 `encoder.py` 와 같은 지위로 둔다. 후보를 내는 도구다.
판단과 근거는 그래프가 갖는다.

    점수 < A_MIN            미지. 그림에서 못 봤다고 한다. 단언하지 않는다
    A_MIN <= 점수 < OK_MIN  되묻기. 사람에게 맞는지 묻는다
    점수 >= OK_MIN          확정 후보. **그래도 .kg 에 자동으로 안 넣는다**

마지막 줄이 핵심이다. 확신이 높아도 옆 파일(`*.그림후보.jsonl`)에 쌓을 뿐,
그래프를 고치는 것은 사람이다. `engine.load()` 의 학습 경로가 표현만 늘리고
"새 노드나 엣지는 절대 만들지 않는" 것과 같은 규칙이다.

노드 이름은 `<행동>_사람_<물체>` 로 짓는다. 그래야 사람이 후보 파일을 읽고
`.kg` 의 [사례] 에 그대로 옮겨 적을 수 있다.
"""
from __future__ import annotations

import json
import os

import engine


def 노드이름(행동, 물체):
    """`ride`, `motorcycle` -> `ride_사람_motorcycle`.

    상자쌍 하나가 노드 하나다. 사람은 늘 한쪽이므로 이름에 박아 둔다."""
    return "%s_사람_%s" % (str(행동).strip(), str(물체).strip())


def 판정(점수, 그래프):
    """세 칸 중 어디인지. 엔진의 임계값을 그대로 쓴다 — 눈금을 따로 두지 않는다."""
    A_MIN = 그래프["임계값"]["A_MIN"]
    OK_MIN = 그래프["임계값"]["OK_MIN"]
    if 점수 < A_MIN:
        return "미지"
    return "되묻기" if 점수 < OK_MIN else "확정후보"


def 엣지후보(예측들, 그래프, 관계=None):
    """HOI 예측 -> 엣지 후보 목록. 그래프는 한 글자도 안 바뀐다.

    예측들: [{"행동", "물체", "점수", "bbox_human", "bbox_object"}, ...]
    관계  : 안 주면 그래프가 선언한 근거관계의 첫 항목을 쓴다. 어휘를 엔진에
            박지 않는다는 규칙 그대로다 — `장면_기본.kg` 는 '관측함' 이다."""
    관계 = 관계 or engine.근거들(그래프)[0]
    사례층 = 그래프.get("사례층", {})
    나옴 = []
    for p in 예측들:
        점수 = float(p["점수"])
        이름 = 노드이름(p["행동"], p["물체"])
        칸 = 판정(점수, 그래프)
        닿는곳 = [d for r, d in 그래프.get("adj", {}).get(이름, ()) if r == 관계]
        나옴.append({
            "노드": 이름, "관계": 관계, "점수": round(점수, 4), "판정":칸,
            # 이미 그래프에 있는 노드인가. 없으면 사람이 [사례] 에 적어야 한다.
            "그래프에있음": 이름 in 사례층,
            "닿는곳": 닿는곳,
            "근거": {"bbox_human": p.get("bbox_human"), "bbox_object": p.get("bbox_object"),
                     "행동": p["행동"], "물체": p["물체"]},
        })
    나옴.sort(key=lambda x: -x["점수"])
    return 나옴


def 후보쓰기(그래프경로, 후보들, 그림=None):
    """옆 파일에 쌓는다. `.kg` 는 안 건드린다.

    엔진이 미지 발화를 `*.미지.log` 에 쌓아 기획자가 읽게 하는 것과 같은 자리다."""
    경로 = os.path.splitext(engine._길(그래프경로))[0] + ".그림후보.jsonl"
    with open(경로, "a", encoding="utf-8") as f:
        for c in 후보들:
            f.write(json.dumps(dict(c, 그림=그림), ensure_ascii=False) + "\n")
    return 경로


def 물어보기(예측들, 그래프):
    """후보를 사람 말로. 그래프의 [대사] 만 쓴다 — 여기서 문장을 짓지 않는다.

    확정후보라도 '봤다' 고만 하지 '그렇다' 고 단언하지 않는다. 그래프에 없는
    노드면 더더욱 — 아직 이 그래프가 모르는 것이다."""
    말 = 그래프["대사"]
    후보 = 엣지후보(예측들, 그래프)
    쓸것 = [c for c in 후보 if c["판정"] != "미지"]
    if not 쓸것:
        return 말.get("미지") or 말["B2"], 후보
    으뜸 = 쓸것[0]
    if not 으뜸["그래프에있음"]:
        # 분류기는 봤다는데 그래프가 모르는 것. 지어내지 않고 모른다고 한다.
        return (말.get("미지") or 말["B2"]), 후보
    if 으뜸["판정"] == "되묻기":
        return 말["A"].format(claim=으뜸["닿는곳"][0] if 으뜸["닿는곳"] else 으뜸["노드"]), 후보
    if not 으뜸["닿는곳"]:
        return 말["근거없음"].format(claim=으뜸["노드"]), 후보
    return 말["인정"].format(ev=으뜸["노드"], claim=으뜸["닿는곳"][0]), 후보


def _selfcheck():
    g = engine.load("graphs/장면_기본.kg")
    assert engine.근거들(g) == ("관측함",), engine.근거들(g)

    # 1) 세 칸이 엔진 임계값 그대로 갈린다
    assert 판정(0.10, g) == "미지" and 판정(0.55, g) == "되묻기" and 판정(0.90, g) == "확정후보"

    # 2) 확신이 높아도 그래프는 한 글자도 안 바뀐다. 이 파일의 존재 이유다.
    엣지전 = list(g["엣지"])
    사례전 = dict(g["사례층"])
    후보 = 엣지후보([{"행동": "ride", "물체": "오토바이", "점수": .97,
                      "bbox_human": [0, 0, 10, 20], "bbox_object": [5, 5, 15, 25]}], g)
    assert g["엣지"] == 엣지전 and g["사례층"] == 사례전, "그래프가 바뀌었다"
    assert 후보[0]["노드"] == "ride_사람_오토바이" and 후보[0]["관계"] == "관측함"
    assert 후보[0]["그래프에있음"] and 후보[0]["닿는곳"] == ["탈것을탐"], 후보[0]

    # 3) 그래프가 모르는 물체는 확신 1.0 이어도 단언하지 않는다
    말, _c = 물어보기([{"행동": "ride", "물체": "우주선", "점수": 1.0}], g)
    assert 말 == g["대사"]["미지"], 말

    # 4) 아는 것은 그래프 [대사] 로 답한다. 문장은 그래프 것이지 여기 것이 아니다.
    말, _c = 물어보기([{"행동": "ride", "물체": "오토바이", "점수": .97}], g)
    assert "탈것을탐" in 말 and "ride_사람_오토바이" in 말, 말
    # 애매하면 되묻는다
    말, _c = 물어보기([{"행동": "ride", "물체": "오토바이", "점수": .55}], g)
    assert 말.startswith("혹시"), 말
    # 낮으면 못 봤다고 한다
    말, _c = 물어보기([{"행동": "ride", "물체": "오토바이", "점수": .10}], g)
    assert 말 == g["대사"]["미지"], 말

    # 5) 관계 어휘는 그래프가 정한다. 엔진에도 여기에도 안 박혀 있다.
    assert 엣지후보([{"행동": "hold", "물체": "컵", "점수": .9}], g)[0]["관계"] == "관측함"

    print("selfcheck ok")


if __name__ == "__main__":
    import sys
    if "--check" in sys.argv:
        _selfcheck()
    else:
        print(__doc__)
