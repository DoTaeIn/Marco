def _이름그대로(g, 질문, 제외=None):
    """질문에 노드 이름이 그대로 들어 있으면 그것을 쓴다.

    개념망으로 상위어가 하위어의 표현을 들고 있으면 '공소기각' 을 물었는데
    '기각' 이 답한다. 자기 이름이 질문에 있으면 자기가 이겨야 한다."""
    t = "".join(질문.split())
    # 공백을 지운 자리에서 원문 자리로 돌아오는 표. 경계 판정은 원문에서 해야 한다 —
    # 지운 문자열에서 앞 글자를 보면 '국가에 손해배상' 의 '손해배상' 이
    # 앞이 '에' 라는 이유로 낱말 중간 취급을 받아 통째로 사라진다.
    자리 = [i for i, ch in enumerate(질문) if not ch.isspace()]
    맞음 = []
    for n in g["노드"]:
        if n == 제외 or len(n) < 2:
            continue
        키 = "".join(n.split())
        i = t.find(키)
        # 앞 글자가 한글이면 낱말 중간을 자른 것이다.
        # '해고가' 안에서 '고가' 를 뽑으면 엉뚱한 노드로 간다.
        while i >= 0:
            앞 = 자리[i] - 1
            # 원문에서도 붙어 있어야 한다. 공백을 지운 자리에서 찾으면
            # '해고 예고 기간' 안에서 '예고기간'(행정절차법)이 걸린다.
            # 이름 자체에 공백이 있는 노드(법 이름)는 예외다.
            붙음 = 자리[i + len(키) - 1] - 자리[i] == len(키) - 1
            if (붙음 or 키 != n) and (앞 < 0 or not ("가" <= 질문[앞] <= "힣")):
                맞음.append(n)
                break
            i = t.find(키, i + 1)
    if not 맞음:
        return []
    v = _vec(질문)
    # 긴 이름이 먼저다(더 구체적이다). 같은 길이면 질문에 가까운 쪽 —
    # '해고 절차' 에서 둘 다 두 글자다.
    return sorted(맞음, key=lambda n: (-len(n), -float((g["vec"][n] @ v).max())))


def _자모(말):
    """한글을 자모로 푼다. 오타는 대개 자모 하나 차이라 글자 단위로는 안 보인다.
    '해고' 와 '해구' 는 글자로 보면 완전히 다르지만 자모로 보면 ㅗ/ㅜ 하나다."""
    out = []
    for c in 말:
        k = ord(c) - 0xAC00
        if 0 <= k < 11172:
            out += [k // 588, (k % 588) // 28, k % 28]
        else:
            out.append(c)
    return out


def _자모거리(a, b, 최대=2):
    """자모 단위 편집거리. 멀면 일찍 포기한다."""
    x, y = _자모(a), _자모(b)
    if abs(len(x) - len(y)) > 최대:
        return 최대 + 1
    d = list(range(len(y) + 1))
    for i, p in enumerate(x, 1):
        앞, d[0] = d[0], i
        for j, q in enumerate(y, 1):
            앞, d[j] = d[j], min(d[j] + 1, d[j - 1] + 1, 앞 + (p != q))
        if min(d) > 최대:
            return 최대 + 1
    return d[-1]


def 오타고침(g, 말, 최대거리=1):
    """그래프가 아는 말 중 자모 하나 차이인 것. 없으면 None.

    재보니 오타 8건이 전부 자모거리 1 이고, 진짜 딴 말(고양이·피카츄)은
    6 이상이었다. 그래서 1 로 자르면 오타만 잡고 딴 얘기는 안 건드린다.

    후보는 길이가 비슷하고 첫 글자 초성이 같은 것만 본다 — 전부 재면
    노드 7천 개에 대해 매번 편집거리를 돌게 된다."""
    아는말 = g.get("_아는말")
    if 아는말 is None:
        아는말 = {}
        for n in g["노드"]:
            아는말.setdefault(len(n), []).append(n)
        # 흔한 것부터 본다. '해구' 는 '해고' 와도 '해부' 와도 자모 하나
        # 차이라 순서를 안 정하면 아무거나 걸린다. 문서에 자주 나오는 쪽이
        # 오타의 원래 말일 가능성이 높다.
        무게 = {n: (g["메타"].get(n, {}).get("빈도") or 0) for n in g["노드"]}
        for L in 아는말:
            아는말[L].sort(key=lambda n: -무게.get(n, 0))
        g["_아는말"] = 아는말
    if not 말 or len(말) < 2:
        return None
    # 조사가 붙은 채로 오면 못 찾는다 ('해구가' 는 노드가 아니다).
    # 뒤에서 한 글자씩 떼어 보면서 아는 말에 닿는지 본다.
    for 끝 in range(len(말), max(len(말) - 2, 1), -1):
        토막 = 말[:끝]
        최고, 점 = None, 최대거리 + 1
        for L in (len(토막) - 1, len(토막), len(토막) + 1):
            for n in 아는말.get(L, ()):
                d = _자모거리(토막, n, 최대거리)
                if d < 점:                # 같은 거리면 앞엣것(더 흔한 것)이 이긴다
                    최고, 점 = n, d
                    if d == 0:
                        break
        if 최고 and 점 > 0:               # 거리 0 이면 오타가 아니라 아는 말이다
            return 최고
    return None


