_제목줄 = re.compile(r"^(#{1,6})\s+(.+?)\s*$")
_번호줄 = re.compile(r"^\s*(\d+)[.)]\s+(.+)$")
_불릿줄 = re.compile(r"^\s*[-*]\s+(.+)$")
_코드울 = re.compile(r"^\s*```")


def 절차읽기(경로들):
    """문서에서 순서 있는 대목을 뽑는다. -> [{제목, 단계[], 출처, 결}]

    절차는 관계로 흩어 놓으면 순서를 잃는다. '판정 밴드를 추가하려면' 의 답은
    'judge 를 고치고, 대사 키를 넣고, 검사를 더한다' 인데, 각각을 따로 아는
    것과 순서를 아는 것은 다르다.

    그래서 원문의 순서를 그대로 들고 온다. 번호 목록·불릿·bash 블록은 이미
    순서가 있는 글이고, 쪼개지 않고 통째로 보관하면 지어낼 여지가 없으면서
    순서가 살아 있다.

    이어지는 줄은 앞 항목에 붙인다. 마크다운은 한 항목을 여러 줄에 걸쳐
    쓰는 일이 흔해서, 안 붙이면 '회귀 문항이 1개 늘고,' 처럼 문장이 잘린다.

    제목은 상위 제목까지 함께 들고 있는다('개발 > 8. 기여하기 좋은 곳').
    절 제목만으로는 무엇에 대한 절차인지 모를 때가 많다."""
    묶음 = []
    for p in (경로들 if isinstance(경로들, (list, tuple)) else [경로들]):
        p = _길(p)
        대상 = ([os.path.join(p, f) for f in sorted(os.listdir(p))
                 if f.endswith(".md")] if os.path.isdir(p) else [p])
        for f in 대상:
            이름 = os.path.splitext(os.path.basename(f))[0]
            위 = {}                      # 깊이 -> 제목
            제목, 깊이, 단계, 코드안 = None, 0, [], False
            표줄, 산문 = set(), []
            def 맺기():
                if 제목 and len(단계) >= 2:
                    길 = [위[d] for d in sorted(위) if d < 깊이] + [제목]
                    묶음.append({"제목": " > ".join([이름] + 길[-2:]),
                                 "단계": list(단계), "출처": 이름,
                                 # 표는 절차가 아니라 조회다. 순서가 뜻이 없고
                                 # 묻는 사람이 원하는 것은 맞는 한 줄이다.
                                 "표": len(표줄) > len(단계) // 2,
                                 # 매칭은 절 전체로, 답은 단계로. 'PR 전에 위
                                 # 넷이 통과해야' 는 산문에 있어서, 산문을
                                 # 안 보면 'PR 전에' 라는 물음이 못 찾는다.
                                 "본문": " ".join(산문)[:600]})
            for 줄 in open(f, encoding="utf-8").read().split(chr(10)):
                if _코드울.match(줄):
                    코드안 = not 코드안
                    continue
                m = _제목줄.match(줄)
                if m and not 코드안:
                    맺기()
                    깊이 = len(m.group(1))
                    for d in [k for k in 위 if k >= 깊이]:
                        위.pop(d)
                    제목, 단계, 표줄, 산문 = m.group(2).strip(), [], set(), []
                    위[깊이] = 제목
                    continue
                if 코드안:
                    t = 줄.strip()
                    if t and not t.startswith("#"):
                        단계.append(t)
                    continue
                m = _번호줄.match(줄) or _불릿줄.match(줄)
                if m:
                    t = m.group(m.lastindex).strip()
                    if len(t) > 4:
                        단계.append(t)
                elif 줄.strip().startswith("|") and 줄.count("|") >= 3:
                    # 표도 절차다. 이 저장소 문서는 '무엇을 하려면 어디를
                    # 본다' 를 표로 적는다 — 표를 버리면 그 답이 통째로 없다.
                    칸 = [c.strip() for c in 줄.strip().strip("|").split("|")]
                    if 칸 and not all(set(c) <= set("-: ") for c in 칸):
                        t = " — ".join(c for c in 칸 if c)
                        if len(t) > 4:
                            단계.append(t)
                            표줄.add(len(단계) - 1)
                elif 단계 and 줄.startswith(("  ", "\t")) and 줄.strip():
                    단계[-1] = 단계[-1].rstrip() + " " + 줄.strip()
                elif 줄.strip():
                    산문.append(줄.strip())
            맺기()
    return 묶음


def 절차찾기(묶음, 질문, 최소=0.35, 개수=1):
    """질문에 맞는 절차. 뜻과 글자를 함께 본다.

    뜻(임베딩)만 보면 'PR 전에 뭘 해야 해' 가 '불변식' 절로 샜다. 절차를
    묻는 말에는 'PR'·'판정 밴드' 처럼 그대로 적힌 낱말이 들어 있는 일이
    많아, 글자가 겹치는지를 함께 봐야 한다.

    여기가 이 기능에서 가장 약한 자리다. 라벨 기준 3/7 이고, 노드 고르기에서
    쓴 숙고(후보 다섯을 각각 밀어보기)를 그대로 옮겨봤지만 안 통했다 —
    단계 점수를 섞는 비율을 0/30/50% 로, 명령이 든 절을 밀어주는 가산을
    0/0.03 으로, 표에 벌점을 0/0.05 로 돌려봤는데 어느 조합도 3/7 을 못
    넘었다(1~3/7). 숙고가 노드에서는 3% -> 6% 를 회수했는데 절에서는 아니다.

    노드는 '이 노드의 발췌가 질문에 답하나' 라는 검증 신호가 있었다. 절에는
    그만한 신호를 아직 못 찾았다. 다음에 볼 것은 질문의 종류(무엇/어떻게/
    어디)를 먼저 가르고 종류별로 다른 절을 보는 쪽이다."""
    if not 묶음:
        return None
    v = _vec(질문)
    낱말 = [w for w in re.findall(r"[가-힣A-Za-z]{2,}", 질문)
            if not any(t in w or w in t for t in (말투.get("질문틀") or []))]
    # 자료에 아예 없는 말이 남으면 딴 얘기다 — 그래프 쪽 _모르는말 과 같은
    # 수법이다. 이 문이 없으면 '코틀린 퀵정렬' 에 러스트 코드를 내준다.
    # 다국어 코드 자료로 재보니 없는 조합 5개를 5개 다 지어냈다.
    바다 = 묶음[0].get("_바다")
    if 바다 is None:
        바다 = " ".join(x["제목"] + " " + x.get("본문", "") + " "
                        + " ".join(x["단계"]) for x in 묶음)
        묶음[0]["_바다"] = 바다
    어미 = 말투.get("어미") or []
    떼는조사 = 말투.get("떼는조사") or []

    def 아나(w, 글):
        if any(w.endswith(e) for e in 어미):
            return True     # 서술어는 딴 얘기의 증거가 못 된다
        # 조사만 뗀다. 아무 데서나 자르면 '자바스크립트로' 가 '자바' 로
        # 걸려서 자바 코드를 내주고, 두 글자에서 멈추면 'C로' 가 안 걸린다.
        # 띄어쓰기는 뜻이 아니다 — 자료의 '이진 검색' 과 물음의 '이진검색'
        # 은 같은 말이다. 뗀 채로 견준다.
        붙 = 글.replace(" ", "")
        if w in 붙:
            return True
        return any(w.endswith(j) and w[:-len(j)] in 붙 for j in 떼는조사)
    if not all(아나(w, 바다) for w in 낱말):
        return None if 개수 == 1 else []

    점수 = []
    for x in 묶음:
        단계글 = " ".join(x["단계"])[:400]
        산문글 = x.get("본문", "")[:400]
        # 제목이 가장 세고 산문이 가장 약하다. 제목이 '무엇을 하는 대목인가'
        # 이고 산문은 곁가지라, 산문을 같은 무게로 보면 엉뚱한 절로 샌다.
        뜻 = max(float(_vec(x["제목"]) @ v),
                 0.9 * float(_vec(단계글) @ v) if 단계글 else 0.0,
                 0.5 * float(_vec(산문글) @ v) if 산문글 else 0.0)
        본문 = x["제목"] + " " + 단계글 + " " + 산문글
        겹침 = (sum(1 for w in 낱말 if w in 본문) / len(낱말)) if 낱말 else 0.0
        점수.append((뜻 + 0.25 * 겹침, x))   # 글자가 겹치면 조금 밀어준다
    점수.sort(key=lambda p: -p[0])
    # 자료에는 있는데 고른 절에는 없고 다른 절 제목에 있는 말 — 묻는 사람은
    # 그 다른 절을 물었고 거기에 답이 없다. '러스트로 BFS' 가 그렇다.
    제목바다 = " ".join(y["제목"] for y in 묶음)

    def 어긋나(x):
        글 = x["제목"] + " " + x.get("본문", "") + " " + " ".join(x["단계"])
        남 = [w for w in 낱말
             if not any(w.endswith(e) for e in 어미) and not 아나(w, 글)]
        return any(아나(w, 제목바다) for w in 남)
    골라 = [x for c, x in 점수[:개수] if c >= 최소 and not 어긋나(x)]
    if 개수 == 1:
        return 골라[0] if 골라 else None
    return 골라


def 절차답(x, 배수=1, 질문=None):
    """원문 그대로 낸다. 지어낸 것이 없다.

    절차는 순서가 뜻이므로 차례대로 낸다. 표는 순서가 뜻이 없고 묻는 사람이
    원하는 것은 맞는 한 줄이라, 가장 가까운 줄을 앞세우고 나머지를 곁들인다."""
    줄 = ["%s" % x["제목"]]
    끝 = 6 * 배수
    단계 = x["단계"]
    if x.get("표") and 질문:
        v = _vec(질문)
        차례 = sorted(range(len(단계)),
                      key=lambda i: -float(_vec(단계[i]) @ v))
        고름 = [단계[i] for i in 차례[:끝]]
        줄.append("  → " + 고름[0])
        for t in 고름[1:3 * 배수]:
            줄.append("    (곁: %s)" % t)
        return chr(10).join(줄)
    for i, t in enumerate(단계[:끝], 1):
        줄.append("  %d. %s" % (i, t))
    if len(단계) > 끝:
        줄.append("  … 그 밖에 %d단계 더 (자세히 라고 하면 더 본다)"
                  % (len(단계) - 끝))
    return chr(10).join(줄)


_코드이름 = re.compile(r"`([A-Za-z_가-힣][A-Za-z0-9_가-힣]*)\(?\)?`"
                      r"|\b([a-z_][a-z0-9_]{3,})\(\)")


def _코드찾기(코드g, 이름):
    """코드 그래프에서 이름에 맞는 노드. 함수명은 표기가 흔들린다."""
    후보 = [이름, 이름.rstrip("()"), 이름 + "()"]
    for n in 코드g["노드"]:
        라벨 = 코드g["메타"].get(n, {}).get("label") or n
        if 라벨 in 후보 or n in 후보 or n.split("_")[-1] in 후보:
            return n
    return None


def 엮은답(질문, 절차묶음, 코드g=None, 배수=1, 곁수=2):
    """절차와 코드를 엮어 한 답으로 낸다.

    문서는 '무엇을 어떤 순서로' 를 알고, 코드 그래프는 '그것이 어디 있고
    무엇을 건드리는지' 를 안다. 둘을 따로 물으면 사람이 머리로 이어야 한다.

    엮되 지어내지 않는다. 단계는 문서 원문 그대로이고, 위치와 호출은 코드
    그래프의 엣지 그대로다. 조각마다 어디서 왔는지가 남는다."""
    후보들 = 절차찾기(절차묶음, 질문, 개수=곁수 + 1)
    if not 후보들:
        return None
    x = 후보들[0]
    줄 = ["## %s" % x["제목"], ""]
    끝 = 6 * 배수
    단계 = x["단계"]
    if x.get("표"):
        v = _vec(질문)
        단계 = sorted(단계, key=lambda t: -float(_vec(t) @ v))[:끝]
    else:
        단계 = 단계[:끝]

    본것 = set()
    for i, t in enumerate(단계, 1):
        줄.append("%d. %s" % (i, t))
        if not 코드g:
            continue
        이름들 = [a or b for a, b in _코드이름.findall(t)]
        for 이름 in 이름들[:3 * 배수]:
            if 이름 in 본것:
                continue
            본것.add(이름)
            n = _코드찾기(코드g, 이름)
            if not n:
                continue
            m = 코드g["메타"].get(n, {})
            자리 = "%s %s" % (m.get("file", ""), m.get("loc", "")) if m.get("file") else ""
            나감, 들옴 = _인접(코드g)
            부름 = [y for r, y in 나감.get(n, ()) if r == "calls"][:3 * 배수]
            불림 = [y for r, y in 들옴.get(n, ()) if r == "calls"][:2 * 배수]
            조각 = ["   · `%s`" % 이름]
            if 자리:
                조각.append("— %s" % 자리.strip())
            if 부름:
                조각.append("· 부른다: %s" % ", ".join(부름))
            if 불림:
                조각.append("· 불린다: %s" % ", ".join(불림))
            if len(조각) > 1:
                줄.append(" ".join(조각))
    if len(x["단계"]) > 끝:
        줄.append("")
        줄.append("… 그 밖에 %d단계 더." % (len(x["단계"]) - 끝))
    # 어느 절이 답인지 고르는 정확도가 낮다(라벨 기준 3/7). BM25·숙고·절 유형
    # 을 다 재봤지만 아무것도 이걸 못 넘었고, 문제가 일곱 개뿐이라 더 맞추는
    # 것은 잡음을 쫓는 일이다. 그래서 순위를 감추지 않고 다음 후보를 같이
    # 내놓는다 — 확신이 없으면 되묻는다는 이 엔진의 태도 그대로다.
    곁 = 후보들[1:]
    if 곁:
        줄.append("")
        줄.append("이 절이 아니라면: " + " / ".join(y["제목"] for y in 곁))
    return chr(10).join(줄)


def 대화질문(질문, 기억):
    """대화 자체에 대한 물음이면 대화 기억에서 답한다. -> 답 또는 None.

    지식 그래프는 세상에 대한 사실이고, 대화 그래프는 이 사람에 대한 사실이다.
    '아까 뭐 물어봤지' 는 세상 지식으로는 못 답하지만 대화 기록에는 적혀 있다.
    그래서 근거가 있고, 몇 번째 턴인지까지 댈 수 있다 — 영수증이 붙는다.

    잡담에 답하는 첫 걸음이다. 잡담이라고 다 근거가 없는 것은 아니다."""
    if not 기억 or not 기억.turn:
        return None
    틀 = 말투.get("_대화질문")
    if not 틀 or not 틀.search(질문):
        return None
    # '처음' 을 먼저 본다. '처음에 뭐 물어봤어' 는 둘 다 걸리는데
    # 묻는 사람이 알고 싶은 것은 처음이다. 좁은 것이 먼저다.
    if re.search(r"처음|첫\s*(질문|말)", 질문):
        if not 기억.흐름:
            return "아직 아무것도 안 물었다."
        return "처음 물은 것은 「%s」 였다." % 기억.흐름[0][0]
    if re.search(r"뭐\s*물어|무엇을\s*물어|뭘\s*물어|물어봤", 질문):
        앞 = [q for q, _t in 기억.흐름][-3:]
        if not 앞:
            return "아직 아무것도 안 물었다."
        return "방금까지 %s 하고 물었다." % ", ".join("「%s」" % q for q in 앞)
    if re.search(r"무슨\s*(얘기|이야기|말)|어디까지|무슨\s*주제", 질문):
        뜨 = 기억.뜨거운(4)
        if not 뜨:
            return "아직 이야기한 것이 없다."
        return "%d턴째이고 %s 이야기를 하고 있었다." % (기억.turn, ", ".join(뜨))
    if re.search(r"오타|잘못\s*(썼|친)|틀리게", 질문):
        if not 기억.오타:
            return "고친 오타가 없다."
        return "%s 로 고쳐 두었다." % ", ".join(
            "「%s」는 「%s」" % (a2, b2) for a2, b2 in 기억.오타.items())
    return None


def _맥락채우기(질문, 기억):
    """주어가 빠진 질문에 아까 이야기하던 것을 넣는다. -> (채운 질문, 주어)

    재순위로는 안 된다. '왜 그래야 해' 는 '해고' 와 닮은 구석이 없어서
    가산을 얼마를 줘도 순위가 안 바뀐다. 주어가 아예 없으므로 넣어줘야 한다.
    engine.py 의 대명사풀기와 같은 수법이고, 다른 점은 직전 세 턴이 아니라
    대화 전체에서 가장 살아 있는 것을 쓴다는 것이다."""
    틀 = 말투.get("_주어없음")
    if not 기억 or not 틀 or not 틀.search(질문):
        return 질문, None
    뜨 = 기억.뜨거운(1)
    if not 뜨:
        return 질문, None
    return "%s %s" % (뜨[0], 질문), 뜨[0]


def 물어보기(g, 질문, 기억=None):
    """문장 -> 설명. 판정이 아니라 안내다.

    graphify 는 여기서 LLM 에 서브그래프를 넘겨 답을 쓰게 한다.
    이 엔진은 그래프에 있는 것만 골라 조립한다 — 지어내지 않고 GPU 도 안 쓴다."""
