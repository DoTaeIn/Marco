def 의도(질문):
    """질문이 무엇을 묻는지 고른다. 앞에 오는 것이 이긴다."""
    t = "".join(질문.split())
    맞은것 = []
    for k, v in 의도표:
        키 = "".join(k.split())
        i = t.find(키)
        if i >= 0:
            # 같은 자리에서 겹치면 긴 쪽이 이긴다. '어디' 가 '어디서 쓰' 를
            # 가로채면 위치를 묻는 것으로 오해한다.
            맞은것.append((i, -len(키), v))
    return min(맞은것)[2] if 맞은것 else "정의"


def _인접(g):
    """엣지를 노드별로 한 번만 접어둔다.

    지식 그래프는 엣지가 37만 개다. 질문마다 전수 스캔하면 설명 한 번에
    166ms 가 든다 — 벡터 계산(16ms)보다 열 배 비싸다."""
    if "_인접" not in g:
        나감, 들옴 = {}, {}
        for x, r, y in g["엣지"]:
            나감.setdefault(x, []).append((r, y))
            들옴.setdefault(y, []).append((r, x))
        g["_인접"] = (나감, 들옴)
    return g["_인접"]


def 잇는길(g, a, b, 최대=5, 뺄관계=("같은조문",)):
    """두 노드 사이 최단 경로. 관계 이름을 그대로 들고 온다.

    '같은조문' 은 기본으로 뺀다. 한 대목에 함께 나왔다는 것뿐이라 두 홉만 타면
    아무 개념이나 이어진다 — 이어졌다는 말이 뜻을 잃는다."""
    나감, 들옴 = _인접(g)
    def 갈곳(n):
        return ([(r, y, True) for r, y in 나감.get(n, ()) if r not in 뺄관계] +
                [(r, x, False) for r, x in 들옴.get(n, ()) if r not in 뺄관계])
    앞, q = {a: None}, deque([a])
    while q:
        n = q.popleft()
        if n == b:
            break
        for r, m, 정 in 갈곳(n):
            if m not in 앞:
                앞[m] = (n, r, 정)
                q.append(m)
    if b not in 앞:
        return None
    길 = []
    n = b
    while 앞[n]:
        p, r, 정 = 앞[n]
        길.append((p, r, n, 정))
        n = p
    길.reverse()
    return 길 if len(길) <= 최대 else None


def _대목이름(출처):
    """'김치찌개 / 두부(두부)' -> '김치찌개 / 두부'. 괄호 반복을 없앤다."""
    m = re.match(r"^(.*?)\((.*)\)$", 출처)
    if m and m.group(1).rstrip().endswith(m.group(2)):
        return m.group(1).rstrip()
    return 출처


def 발췌고르기(g, 이름, 질문=None, 뜻=None):
    """그 개념의 문장들 중 질문에 가장 가까운 것을 고른다.

    같은 개념이 여러 대목에 다른 정보로 나온다. '두부' 는 자기 절에서 정의이지만
    김치찌개 절에서는 '마지막에 넣어야 부서지지 않는다' 이다.
    질문을 보고 골라야 '언제 넣어?' 에 정의를 주는 일이 없다.

    후보가 한 노드분(보통 2~6문장)뿐이라 그때 인코딩해도 비용이 거의 없다.
    다만 한 문장씩 부르면 모델 호출 8번이다 — 한 번에 넣는다."""
    후보 = (g["메타"].get(이름) or {}).get("발췌") or []
    if isinstance(후보, str):                       # 옛 형식
        return {"글": 후보, "곳": (g["메타"][이름] or {}).get("file")}
    if not 후보:
        return None
    if not 질문 or len(후보) == 1:
        return 후보[0]
    표지 = 뜻표지.get(뜻 or 의도(질문), ())
    if len(후보) > 8:
        # 인코딩 비용은 후보 수에 그대로 비례한다. 8개로 자르되, 자르기 전에
        # 표지로 순서를 바꾼다 — 표지는 문자열 검사라 공짜다.
        걸림 = [x for x in 후보 if any(t in x["글"] for t in 표지)] if 표지 else []
        나머지 = [x for x in 후보 if x not in 걸림]
        후보 = (걸림 + 나머지)[:8]
    v = _vec(질문)
    V = _model().encode([숫자가리기(x["글"]) for x in 후보],
                        normalize_embeddings=True, show_progress_bar=False)
    best, 점수 = 후보[0], -1.0
    for x, xv in zip(후보, V):
        c = float(xv @ v)
        # 표지 '개수' 에 비례한다. 모든 후보에 하나씩 있으면 보너스가 균일해져
        # 순위가 그대로다 — 실제로 그래서 답이 하나도 안 바뀌었다.
        # 0.025 로는 벡터를 못 이긴다. '개인정보 유출하면 처벌돼?' 에서
        # 벌칙 조문(제70조)이 개인정보를 네 번 부르는 정의 조문에 밀렸다.
        # 무엇을 묻는지는 문장이 얼마나 닮았는지보다 강한 신호다.
        걸린수 = sum(1 for t in 표지 if t in x["글"])
        c += 0.06 * min(걸린수, 4)
        if c > 점수:
            best, 점수 = x, c
    return best


def 설명(g, 이름, 뜻="정의", 최대이웃=5, 질문=None):
    """노드를 묻는 방식에 맞춰 설명한다. 생성이 아니라 조립이다.

    조사는 조립한 부분에만 맞춘다. 인용한 원문은 한 글자도 건드리지 않는다 —
    '그 밖에 이 법에 따라' 의 '이' 를 조사로 보고 '가' 로 고친 적이 있다."""
    나감, 들옴 = _인접(g)
    나가는, 들어오는 = 나감.get(이름, []), 들옴.get(이름, [])
    m = g["메타"].get(이름, {})
    줄 = []

    맺기 = lambda 목록: 조사맞추기(" ".join(목록))

    if 뜻 == "위치":
        if m.get("file"):
            줄.append("%s 는 %s%s 에 있습니다."
                      % (이름, m["file"], (" " + m["loc"]) if m.get("loc") else ""))
        else:
            줄.append("%s 의 위치는 그래프에 기록돼 있지 않습니다." % 이름)
        if m.get("community"):
            줄.append("%s 묶음에 속합니다." % m["community"])
        return 맺기(줄)

    if 뜻 == "이유":
        근거 = [(r, x) for r, x in 들어오는 if r == "rationale_for"] +               [(r, y) for r, y in 나가는 if r == "rationale_for"]
        if 근거:
            줄.append("%s 의 근거로 %s 가 기록돼 있습니다."
                      % (이름, ", ".join(x for _, x in 근거)))
        else:
            줄.append("%s 에 대한 근거는 그래프에 없습니다." % 이름)
            이웃 = [y for _, y in 나가는[:3]]
            if 이웃:
                줄.append("대신 %s 와 이어져 있습니다." % ", ".join(이웃))
        return 맺기(줄)

    if 뜻 == "쓰는곳":
        쓴다 = [(r, x) for r, x in 들어오는
                if r in ("imports", "imports_from", "calls", "references", "contains")]
        if 쓴다:
            줄.append("%s 는 %s 에서 씁니다."
                      % (이름, ", ".join("%s(%s)" % (x, r) for r, x in 쓴다[:최대이웃])))
        else:
            줄.append("%s 를 쓰는 곳이 그래프에 없습니다." % 이름)
        return 맺기(줄)

    if 뜻 == "이웃":
        가까운 = 나가는[:최대이웃] + 들어오는[:최대이웃]
        if 가까운:
            줄.append("%s 는 %s 와 엮여 있습니다."
                      % (이름, ", ".join(sorted({y for _, y in 가까운}))))
        else:
            줄.append("%s 는 연결된 것이 없습니다." % 이름)
        return 맺기(줄)

    정의처 = m.get("정의처") or []
    뽑음 = 발췌고르기(g, 이름, 질문, 뜻)

    # 원문을 인용해서 답한다. '어디서 다룹니다' 는 출처지 답이 아니다.
    # 지어내지 않고 그대로 옮긴다 — 여전히 선택이지 생성이 아니다.
    if 뽑음 and 뽑음.get("글"):
        원문 = 뽑음["글"]
        줄 = []
        어디 = _대목이름(뽑음.get("곳") or (정의처 or [m.get("file")])[0] or "")
        모두 = len((m.get("발췌") or []))
        if 어디:
            줄.append("— %s%s" % (어디,
                      " 외 %d곳" % (모두 - 1) if 모두 > 1 else ""))
        곁 = [y for r, y in 나가는 if r == "설명함"][:4] or              [y for r, y in 나가는][:4]
        if 곁:
            줄.append("함께 나오는 것: %s." % ", ".join(곁))
        return (원문 + " " + 맺기(줄)).rstrip()

    if 정의처:
        줄.append("%s 는 %s 에서 다룹니다%s."
                  % (이름, _대목이름(정의처[0]),
                     " (외 %d곳)" % (len(정의처) - 1) if len(정의처) > 1 else ""))
        다룸 = [y for r, y in 나가는 if r == "설명함"][:5]
        if 다룸:
            줄.append("그 대목은 %s 를 함께 다룹니다." % ", ".join(다룸))
        return 맺기(줄)

    머리 = 이름
    if m.get("community"):
        머리 += " 는 %s 묶음에 속합니다" % m["community"]
    elif m.get("type"):
        머리 += " 는 %s 입니다" % m["type"]
    else:
        머리 += " 입니다"
    if m.get("file"):
        머리 += " (%s%s)" % (m["file"], (" " + m["loc"]) if m.get("loc") else "")
    줄.append(머리 + ".")
    if 나가는:
        줄.append(" ".join(관계문장(r, y, True) + "." for r, y in 나가는[:3]))
    if 들어오는:
        줄.append(" ".join(관계문장(r, x, False) + "." for r, x in 들어오는[:2]))
    if not 나가는 and not 들어오는:
        줄.append("연결된 것이 없습니다.")
    return 맺기(줄)


