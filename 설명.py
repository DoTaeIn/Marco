def graphify읽기(경로, 최대=1200):
    """graphify graph.json -> 이 엔진이 쓸 수 있는 형태.

    graphify 는 그래프를 잘 짓지만 두 가지가 약하다. 자기 문서가 인정한다:
    노드 매칭이 문자열 포함이라 어휘가 어긋나면 0건이 되고, 답변은 LLM 이 쓴다.
    이 엔진은 그 두 자리를 임베딩 매칭과 선택형 응답으로 메운다.

    판정용 그래프가 아니므로 목표·요건이 없다. 설명만 한다."""
    raw = json.load(open(경로, encoding="utf-8"))
    노드, 메타 = {}, {}
    for n in raw.get("nodes", [])[:최대]:
        이름 = n.get("label") or n.get("id")
        if not 이름:
            continue
        예시 = [이름]
        for k in ("norm_label", "community_name", "summary", "description"):
            v = n.get(k)
            if v and isinstance(v, str) and v.lower() != 이름.lower():
                예시.append(v)
        노드[이름] = 예시[:4]
        메타[이름] = {"community": n.get("community_name"),
                      "file": n.get("source_file"),
                      "loc": n.get("source_location"),
                      "type": n.get("file_type")}
    id별 = {n.get("id"): (n.get("label") or n.get("id"))
            for n in raw.get("nodes", [])}
    엣지 = []
    for e in raw.get("links", []) + raw.get("edges", []):
        a, b = id별.get(e.get("source")), id별.get(e.get("target"))
        r = e.get("relation") or e.get("type") or "관련"
        if a in 노드 and b in 노드:
            엣지.append([a, r, b])
    return {"역할": "안내", "목표": None, "설명그래프": True,
            "임계값": {"A_MIN": 0.45, "OK_MIN": 0.58},
            "노드": 노드, "메타": 메타, "엣지": 엣지, "무관층": {}}


def 말투읽기(이름=None):
    """말투를 파일에서 읽는다. 말은 엔진이 아니라 데이터다.

    조사·이음말·관계 말투·주어 생략 판단이 전부 한국어 규칙인데 파이썬에
    박혀 있으면 다른 언어를 쓸 때 엔진을 고쳐야 한다. 그래프를 바꿔 도메인을
    바꾸듯 말투 파일을 바꿔 언어를 바꾼다.

    KG_LANG 환경변수나 인자로 고른다. 기본은 말투/한국어.json 이다."""
    이름 = 이름 or os.environ.get("KG_LANG", "한국어")
    경로 = 이름 if 이름.endswith(".json") else os.path.join("말투", 이름 + ".json")
    with open(_길(경로), encoding="utf-8") as f:
        말 = json.load(f)
    말["_조사자리"] = (re.compile(r"([가-힣]) (%s)(?=[\s.,?!]|$)"
                                  % "|".join(말["조사짝"]))
                       if 말.get("조사짝") else None)
    말["_띄운조사"] = (re.compile(r"([가-힣0-9)]) (%s)(?=[\s.,?!]|$)"
                                  % "|".join(말["붙일조사"]))
                       if 말.get("조사붙임") and 말.get("붙일조사") else None)
    말["_주어없음"] = re.compile(말["주어없음"]) if 말.get("주어없음") else None
    return 말


