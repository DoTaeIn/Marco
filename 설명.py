def _이름그대로(g, 질문, 제외=None):
    """질문에 노드 이름이 그대로 들어 있으면 그것을 쓴다.

    개념망으로 상위어가 하위어의 표현을 들고 있으면 '공소기각' 을 물었는데
    '기각' 이 답한다. 자기 이름이 질문에 있으면 자기가 이겨야 한다."""
    t = "".join(질문.split())
    # 공백을 지운 자리에서 원문 자리로 돌아오는 표. 경계 판정은 원문에서 해야 한다 —
    # 지운 문자열에서 앞 글자를 보면 '국가에 손해배상' 의 '손해배상' 이
    # 앞이 '에' 라는 이유로 낱말 중간 취급을 받아 통째로 사라진다.
    자리 = [i for i, ch in enumerate(질문) if not ch.isspace()]
    맞음 = []
    for n in g["노드"]:
        if n == 제외 or len(n) < 2:
            continue
        키 = "".join(n.split())
        i = t.find(키)
        # 앞 글자가 한글이면 낱말 중간을 자른 것이다.
        # '해고가' 안에서 '고가' 를 뽑으면 엉뚱한 노드로 간다.
        while i >= 0:
            앞 = 자리[i] - 1
            # 원문에서도 붙어 있어야 한다. 공백을 지운 자리에서 찾으면
            # '해고 예고 기간' 안에서 '예고기간'(행정절차법)이 걸린다.
            # 이름 자체에 공백이 있는 노드(법 이름)는 예외다.
            붙음 = 자리[i + len(키) - 1] - 자리[i] == len(키) - 1
            if (붙음 or 키 != n) and (앞 < 0 or not ("가" <= 질문[앞] <= "힣")):
                맞음.append(n)
                break
            i = t.find(키, i + 1)
    if not 맞음:
        return []
    v = _vec(질문)
    # 긴 이름이 먼저다(더 구체적이다). 같은 길이면 질문에 가까운 쪽 —
    # '해고 절차' 에서 둘 다 두 글자다.
    return sorted(맞음, key=lambda n: (-len(n), -float((g["vec"][n] @ v).max())))


def _가까운노드(g, 글, 제외=None):
    v = _vec(글)
    best, score = None, 0.0
    for n in g["노드"]:
        if n == 제외:
            continue
        c = float((g["vec"][n] @ v).max())
        if c > score:
            best, score = n, c
    return best, score


def _주제고르기(질문, 이름들):
    """질문에 노드 이름이 여럿 걸렸을 때 무엇이 주제인가.

    1) 조각을 버린다. '저작권 침해' 의 '저작' 은 '저작권' 의 일부다.
    2) 긴 것이 이긴다. 더 구체적이기 때문이다 — '국가에 손해배상' 은
       '국가' 가 아니라 '손해배상' 이야기다.
    3) 길이가 같으면(계약/취소, 고소/취하) 먼저 나온 쪽이다. 한국어는
       주제를 앞에 둔다 — '계약 취소' 는 계약 이야기지 취소 이야기가 아니다."""
    남 = [n for n in 이름들 if not any(n != m and n in m for m in 이름들)]
    긴것 = max(len(n) for n in 남)
    t = "".join(질문.split())
    return min((n for n in 남 if len(n) == 긴것),
               key=lambda n: t.find("".join(n.split())))


_조사짝 = {"은": ("은", "는"), "는": ("은", "는"), "이": ("이", "가"), "가": ("이", "가"),
           "을": ("을", "를"), "를": ("을", "를"), "과": ("과", "와"), "와": ("과", "와"),
           "으로": ("으로", "로"), "로": ("으로", "로")}
_조사자리 = re.compile(r"([가-힣]) (%s)(?=[\s.,?!]|$)" % "|".join(_조사짝))


def 조사맞추기(글):
    """'저작권 는' -> '저작권 은'. 조립이 끝난 뒤 받침에 맞춘다.

    노드 이름이 무엇일지 미리 알 수 없으니 템플릿에 조사를 박을 수 없다.
    이 그래프는 이름과 조사를 띄어 쓰므로(이름이 전문용어라 붙이면 안 읽힌다)
    앞 글자만 보면 된다."""
    def 고침(m):
        받침 = (ord(m.group(1)) - 0xAC00) % 28 != 0
        return m.group(1) + " " + _조사짝[m.group(2)][0 if 받침 else 1]
    return _조사자리.sub(고침, 글)


def _끝점(g, 글, 제외=None):
    """경로 질문의 한쪽 끝. 이름이 그대로 있으면 그것이 우선이다.

    벡터로만 잡으면 '정당방위' 를 물었는데 '방위' 가 끝점이 된다 —
    개념망이 상위어에 하위어 표현을 붙여 놓기 때문이다."""
    이름 = _이름그대로(g, 글, 제외=제외)
    if 이름:
        n = _주제고르기(글, 이름)
        return n, float((g["vec"][n] @ _vec(글)).max())
    return _가까운노드(g, 글, 제외)


def _함께나오나(g, a, b):
    """이어지지는 않아도 같은 대목에 함께 나올 수 있다. 그것도 사실이다."""
    곳 = lambda n: set((g["메타"].get(n) or {}).get("출처") or [])
    같이 = sorted(곳(a) & 곳(b))
    return 같이[0] if 같이 else None


def _발췌찾기(g, 질문, 최소=None):
    """발췌를 노드를 거치지 않고 바로 찾는다. -> (문장, 곳, 주인노드, 점수)

    지금까지는 질문 -> 노드 -> 그 노드의 발췌 순서였다. 그러면 노드를 틀리는
    순간 발췌도 틀린다. 그런데 법 코퍼스는 조문 하나에 노드가 중앙값 12개라
    노드 고르기가 병목이다 — 주제 적중이 2% 였다.

    발췌를 바로 찾으면 그 병목을 건너뛴다. 같은 시험에서 노드 경유가 1~3%,
    직접 검색이 17%(상위 5 안이면 40%)였다. 열 배다.

    문턱은 그래프의 OK_MIN 을 쓴다. 매직 넘버를 두면 안 된다 — 처음 0.45 로
    했더니 'asdf qwer zxcv'(0.567)와 '내일 날씨 어때'(0.368)가 답을 받았다.
    근거 없이 답하지 않는다는 것이 이 엔진의 전부라 그건 회귀다. 재보니
    무관한 질문은 0.57 이하, 답해야 할 질문은 0.64 이상으로 깨끗이 갈렸다.
    OK_MIN(0.60)이 그 사이에 있고, --tune 이 그래프마다 보정해 준다.

    색인은 처음 물을 때 한 번 만들고 그래프에 붙여 둔다."""
    import numpy as np
    if 최소 is None:
        최소 = g["임계값"]["OK_MIN"]
    표 = g.get("_발췌색인")
    if 표 is None:
        문장, 곳, 주인 = [], {}, {}
        for n, m in g["메타"].items():
            for x in m.get("발췌", ()):
                t = (x.get("글") or "").strip()
                if len(t) > 10 and t not in 주인:
                    문장.append(t)
                    곳[t] = x.get("곳", "")
                    주인[t] = n
        if not 문장:
            g["_발췌색인"] = (None, [], {}, {})
            return None
        P = []
        for i in range(0, len(문장), 256):
            P.append(_model().encode([숫자가리기(t) for t in 문장[i:i + 256]],
                                     normalize_embeddings=True))
        표 = (np.vstack(P), 문장, 곳, 주인)
        g["_발췌색인"] = 표
    P, 문장, 곳, 주인 = 표
    if P is None:
        return None
    점 = P @ _vec(질문)
    i = int(점.argmax())
    if float(점[i]) < 최소:
        return None
    return 문장[i], 곳[문장[i]], 주인[문장[i]], float(점[i])


def 물어보기(g, 질문):
    """문장 -> 설명. 판정이 아니라 안내다.

    graphify 는 여기서 LLM 에 서브그래프를 넘겨 답을 쓰게 한다.
    이 엔진은 그래프에 있는 것만 골라 조립한다 — 지어내지 않고 GPU 도 안 쓴다."""
    뜻 = 의도(질문)
    A_MIN, OK_MIN = g["임계값"]["A_MIN"], g["임계값"]["OK_MIN"]

    if 뜻 == "경로":
        나눔 = [x.strip() for x in re.split(r"[와과랑,]|하고", 질문)
                if len(x.strip()) > 1]
        if len(나눔) >= 2:
            a, ca = _끝점(g, 나눔[0])
            b, cb = _끝점(g, 나눔[1], 제외=a)
            if a and b and min(ca, cb) >= A_MIN:
                # 바로 이어진 것이 있으면 그것이 답이다.
                # 없으면 구조 관계(코드 그래프의 호출·참조 같은 것)로만 이어 본다.
                # '설명함' 은 한 다리만 건너면 무엇이든 잇는다 — '저작권 -> 대통령령
                # -> 음주운전' 같은 것을 관계라고 부르면 관계라는 말이 뜻을 잃는다.
                길 = (잇는길(g, a, b, 최대=1)
                      or 잇는길(g, a, b, 뺄관계=("같은조문", "설명함")))
                if 길:
                    return "경로", 조사맞추기(길설명(g, 길)), a
                곳 = _함께나오나(g, a, b)
                if 곳:
                    return ("경로", 조사맞추기(
                        "%s 와 %s 는 이어지지 않지만 %s 에 함께 나옵니다."
                        % (a, b, _대목이름(곳))), a)
                return "경로", 조사맞추기(
                    "%s 와 %s 는 그래프에서 이어지지 않습니다." % (a, b)), a
        뜻 = "이웃"

    # 두 글자 개념(해고·기각·상법)이 흔하다. 3글자 이상만 받으면
    # '해고는 언제?' 가 '해고' 를 놓치고 '해고사유' 로 샌다.
    그대로 = _이름그대로(g, 질문)
    if 그대로:
        주제 = _주제고르기(질문, 그대로)
        # 이름이 들어 있다고 그 이야기인 것은 아니다. '양자역학' 안에는
        # '양자'(민법)가 들어 있다. 확신이 없으면 벡터 쪽에 넘긴다.
        if float((g["vec"][주제] @ _vec(질문)).max()) >= A_MIN:
            return "설명", 설명(g, 주제, 뜻, 질문=질문), 주제

    best, score = None, 0.0
    for 조각 in 조각내기(질문):
        n, c = _가까운노드(g, 조각)
        if c > score:
            best, score = n, c

    # 노드가 흐리면 발췌를 바로 찾는다. 노드 고르기가 병목이라, 노드를 못
    # 고르겠을 때 포기하는 것보다 대목을 직접 꺼내는 편이 열 배 낫다.
    if score < OK_MIN:
        직 = _발췌찾기(g, 질문)
        if 직 and 직[3] > score:
            문장, 곳, 주인, _c = 직
            return "설명", 조사맞추기("%s%s" % (
                문장, (" — " + _대목이름(곳)) if 곳 else "")), 주인

    if score < A_MIN:
        return "미지", "그건 이 그래프에 없는 이야기입니다.", None
    if score < OK_MIN:
        나감, 들옴 = _인접(g)
        이웃 = sorted({y for _, y in 나감.get(best, ())} |
                      {x for _, x in 들옴.get(best, ())})[:3]
        꼬리 = (" %s 근처 이야기입니다." % ", ".join(이웃)) if 이웃 else ""
        return "A", 조사맞추기("혹시 %s 말씀입니까?%s" % (best, 꼬리)), best
    return "설명", 설명(g, best, 뜻, 질문=질문), best


def 설명채점(g, 최대=400):
    """목표 없는 모드의 정답지. 사람이 라벨을 달지 않는다.

    논증 모드는 판례가 정답지였다 — 사실을 넣고 법원의 결론이 나오는지 본다.
    설명 모드에는 그런 것이 없어서 "무엇이 좋은 답인가" 를 잴 수가 없었다.
    여기서는 원문 자체를 정답지로 쓴다: 각 노드의 발췌는 그 노드를 물었을 때
    나와야 할 문장이다.

    세 가지를 따로 잰다. 난이도가 다르고 뜻이 다르다.

      이름     노드 이름을 그대로 묻는다. 문자열로 찾히므로 거의 다 맞는다.
               이게 낮으면 조회 경로가 깨진 것이다.
      가림     발췌에서 노드 이름을 지우고 묻는다. 문자열 단서가 없으니
               임베딩 매칭만으로 주제를 맞혀야 한다. 이게 진짜 실력이다.
      대목     주제를 틀렸더라도 답에 그 문장이 들어 있으면 맞는 것으로 센다.
               한 문장에 노드가 여럿이면 어느 하나로 귀속시키는 것이 애매한데,
               쓰는 사람이 원하는 것은 옳은 대목이지 옳은 이름표가 아니다.

    노드를 채우면 '대목' 이 오르고 '가림' 은 내린다. 같은 8개 질문으로 통제해
    비교했더니 대목 4/8 -> 6/8, 주제 2/8 -> 0/8 이었다(요리, 8노드 -> 30노드).
    노드가 늘면 답은 좋아지지만 "이 문장의 주인이 누구냐" 가 더 애매해지기
    때문이다. 그래서 그래프를 키우며 개선을 잴 때 '가림/주제' 를 쓰면 안 된다.
    법지식 그래프의 가림 2% 도 노드 7,195개가 서로 경쟁한 결과다.

    '가림' 은 정답지가 시끄럽다는 것을 알고 봐야 한다. 짓기.py 는 한 문장을
    그 안에 든 모든 개념에 붙이므로, 그 문장의 *주제* 가 아닌 노드에도 발췌가
    달린다. '제310조(전세권자의 상환청구권) ... 지출한 금액' 은 상환청구권
    이야기지 지출액 이야기가 아닌데, 지출액의 발췌로도 들어가 있다. 법지식
    그래프에서 가림이 2% 인 것은 절반쯤 이 때문이다. 세 숫자 중 '대목' 이
    가장 믿을 만하고, 개선을 잰다면 그것으로 잰다."""
    이름 = 가림 = 대목 = 총 = 0
    틀린것 = []
    for n in list(g["노드"])[:최대]:
        발췌 = [x.get("글", "") for x in g["메타"].get(n, {}).get("발췌", [])]
        발췌 = [x for x in 발췌 if len(x) > 10]
        if not 발췌:
            continue
        총 += 1
        if 물어보기(g, n)[2] == n:
            이름 += 1
        가린문장 = re.sub(re.escape(n), " ", 발췌[0])
        _의도, 답, 주제 = 물어보기(g, 가린문장)
        if 주제 == n:
            가림 += 1
        elif len(틀린것) < 8:
            틀린것.append((n, 주제, 가린문장[:44]))
        핵심 = re.sub(r"\s+", "", 발췌[0])[:24]
        if 핵심 and 핵심 in re.sub(r"\s+", "", 답 or ""):
            대목 += 1
    return {"총": 총, "이름": 이름, "가림": 가림, "대목": 대목, "틀린것": 틀린것}


def 지식그림(g, 중심=None, 최대=45):
    """설명 그래프(graphify 등)를 Mermaid 로. 관계 종류마다 선이 다르다.

    492노드를 통째로 그리면 못 본다. 중심 노드에서 퍼져나가며 최대 개수까지만 담는다."""
    이웃 = {}
    for a, r, b in g["엣지"]:
        이웃.setdefault(a, []).append((r, b))
        이웃.setdefault(b, []).append((r, a))
    시작 = 중심 or max(이웃, key=lambda n: len(이웃[n]))
    본것, q = {시작}, deque([시작])
    while q and len(본것) < 최대:
        n = q.popleft()
        for _, m in 이웃.get(n, []):
            if m not in 본것 and len(본것) < 최대:
                본것.add(m)
                q.append(m)

    선 = {"설명함": "==>", "같은조문": "-.->", "같은대목": "-.->",
          "contains": "-->", "imports": "==>", "imports_from": "==>",
          "calls": "-->", "references": "-.->", "conceptually_related_to": "-.->",
          "semantically_similar_to": "-.->", "extends": "==>", "cites": "-.->"}
    별명, L = {}, ["flowchart LR"]
    def id(n):
        if n not in 별명:
            별명[n] = "k%d" % len(별명)
        return 별명[n]
    무리 = {}
    for n in sorted(본것):
        무리.setdefault((g["메타"].get(n) or {}).get("community") or "기타", []).append(n)
    for 이름, 들 in 무리.items():
        L.append('  subgraph s%d["%s"]' % (abs(hash(이름)) % 9999, 이름))
        for n in 들:
            L.append('    %s["%s"]' % (id(n), n.replace('"', "")))
        L.append("  end")
    # 32만 엣지짜리 그래프는 부분만 떠도 빽빽하다. 노드마다 몇 개씩만 남긴다.
    나옴, 개수 = set(), {}
    for a, r, b in g["엣지"]:
        if a not in 본것 or b not in 본것 or (a, r, b) in 나옴:
            continue
        if 개수.get(a, 0) >= 4 or 개수.get(b, 0) >= 4:
            continue
        나옴.add((a, r, b))
        개수[a] = 개수.get(a, 0) + 1
        개수[b] = 개수.get(b, 0) + 1
        L.append("  %s %s|%s| %s" % (id(a), 선.get(r, "---"), r, id(b)))
    L.append("  classDef 중심 fill:#1d4ed8,stroke:#1e3a8a,color:#fff")
    L.append("  class %s 중심" % id(시작))
    return "\n".join(L)


